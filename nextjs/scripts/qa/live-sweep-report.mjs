#!/usr/bin/env node
/*
  Turns the JSON ledgers `live-sweep.mjs` writes into the markdown ledger under docs/audit/.

  Severity is mechanical, so two runs of the same data rank the same way:
    P0  an overlap or a clip above the fold, or anywhere inside the header, the hero or a CTA —
        the first screen and the button are what a visitor is asked to trust.
    P1  the same defect below the fold, plus overflow, contrast and sub-44px tap targets.
    P2  leading, the 12px type floor and media with no intrinsic size — cosmetic or CLS.

  A finding is identified by route + width + type + selector, so the same defect at six widths
  is six rows of one id family and can be ticked off together.

  Usage: node scripts/qa/live-sweep-report.mjs [--shots <dir>] [--out <file.md>]
*/

import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const at = argv.indexOf(`--${name}`);
  return at === -1 ? fallback : argv[at + 1];
};
const SHOTS = flag("shots", "D:/CodexProjects/gates-lanes/polish-shots");
const OUT = flag("out", "docs/audit/UI_SWEEP_2026-09-22.md");

const HOT = /header|hero|nav|cta|masthead|lv2-h1|site-header|drop|primary/i;

const severity = finding => {
  if (finding.type === "overlap" || finding.type === "clipping") {
    return finding.aboveFold || HOT.test(finding.selector) ? "P0" : "P1";
  }
  if (finding.type === "overflow" || finding.type === "contrast" || finding.type === "tap-target") return "P1";
  if (finding.type === "http" || finding.type === "error") return "P1";
  return "P2";
};

const ledgers = (await readdir(SHOTS)).filter(name => name.startsWith("ledger-") && name.endsWith(".json"));
const rows = [];
for (const name of ledgers) {
  const ledger = JSON.parse(await readFile(join(SHOTS, name), "utf8"));
  for (const row of ledger.rows) {
    for (const finding of row.findings) {
      rows.push({
        run: basename(name, ".json").replace("ledger-", ""),
        browser: ledger.browser, scheme: ledger.scheme, motion: ledger.motion,
        route: row.route, width: row.width, shot: row.shot,
        severity: severity(finding), ...finding,
      });
    }
  }
}

/* One id per defect, not per measurement: the same selector on the same route is one thing to
   fix whatever width first reported it. */
const families = new Map();
for (const row of rows) {
  /* The text is part of the identity: the selector for a tap target is often just `a`, and
     seven links in one footer are seven things to measure, not one. */
  const key = `${row.route}|${row.type}|${row.selector}|${row.text}`;
  const family = families.get(key) ?? { ...row, widths: new Set(), runs: new Set(), worst: row.severity };
  family.widths.add(row.width);
  family.runs.add(row.run);
  if (row.severity === "P0" || (row.severity === "P1" && family.worst === "P2")) family.worst = row.severity;
  families.set(key, family);
}

const order = { P0: 0, P1: 1, P2: 2 };
const sorted = [...families.values()].sort((a, b) =>
  order[a.worst] - order[b.worst] || a.route.localeCompare(b.route) || a.type.localeCompare(b.type));
sorted.forEach((family, index) => { family.id = `UI-${String(index + 1).padStart(3, "0")}`; });

const counts = { P0: 0, P1: 0, P2: 0 };
for (const family of sorted) counts[family.worst] += 1;

const table = sorted.map(family => [
  family.id, family.worst, family.route, [...family.widths].sort((a, b) => a - b).join("/"),
  [...family.runs].join(" "), family.type, "`" + family.selector.replaceAll("|", "\\|") + "`",
  (family.text ?? "").replaceAll("|", "\\|").slice(0, 48),
  (family.detail ?? "").replaceAll("|", "\\|"),
  family.shot ? family.shot.replaceAll("\\", "/").replace(SHOTS + "/", "") : "—",
].join(" | ")).map(line => `| ${line} |`).join("\n");

const markdown = `<!-- generated by scripts/qa/live-sweep-report.mjs — do not hand-edit the table -->
# UI sweep — tavonel.com, 2026-09-22

Measured against the **deployed** site, not a branch build. ${rows.length} measurements across
${new Set(rows.map(row => row.run)).size} runs collapse to ${sorted.length} distinct defects:
**${counts.P0} P0 · ${counts.P1} P1 · ${counts.P2} P2**.

Method, thresholds and the exclusions that keep the count honest are in
\`nextjs/scripts/qa/live-sweep.mjs\`. Screenshots are under \`${SHOTS}\` (outside the repository).

| id | sev | route | widths | run | type | selector | text | detail | screenshot |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${table}
`;

/* Disposition -- what was fixed, what was deferred and why -- is written by hand and lives in a
   sibling `.notes.md`, so regenerating the table never discards it. */
const notes = await readFile(OUT.replace(/\.md$/, ".notes.md"), "utf8").catch(() => "");
await writeFile(OUT, notes ? `${markdown}\n${notes}` : markdown);
console.log(`${OUT} — ${sorted.length} defects (${counts.P0} P0, ${counts.P1} P1, ${counts.P2} P2) from ${rows.length} measurements`);
