// Real-input end-to-end proving harness for the TAVONEL public v1 API.
//
// Every path below was read out of the site repo, not assumed. Two of them are
// deliberately NOT under /api/v1 because no v1 route exists (see GAPS.md), and
// the chain stops at promotion because promotion has no API-key route at all.
//
// Node 22. No dependencies: global fetch, node:crypto, node:fs.
//
// -----------------------------------------------------------------------------
// This is the growth-campaign copy (WG-032/033/055, 2026-09-11), taken verbatim
// from D:\CodexProjects\uskc-lanes\e2e\prove.mjs (2026-09-06) and extended. That
// original and its receipts are read-only evidence and were not modified.
//
// What is new here, and nothing else:
//   --plan                 the 18-step model and what each step would call, with no
//                          credential read and no call made.
//   EXTERNAL_CONSUMER      step 12: a read of the same active World from outside the
//   PACKAGE_DOWNLOAD       browser. Step 13: the signed package, plus the verdict of
//                          the package verifier that already ships to customers.
//   receipt.journey        the 18 steps with execution / semantic / task recorded
//                          together, from the same function the checker uses.
//   receipt.costAccounting measured: false. Nothing here measures cost, so nothing
