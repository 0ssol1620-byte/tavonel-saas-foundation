import Link from "next/link";
import type { Route } from "next";
import { PublicSitePage } from "@/components/public-site-chrome";
import { pageMetadata } from "@/lib/page-seo";
import {
  GDP_PDF_ARM_LABEL,
  GDP_PDF_ARTIFACT_PATH,
  GDP_PDF_ARTIFACT_SHA256,
  GDP_PDF_PAGE_ARMS,
  gdpPdfDeltaSentence,
  gdpPdfDeviations,
  gdpPdfFailureNotes,
  gdpPdfHeadline,
  gdpPdfPercent,
  gdpPdfPoints,
  gdpPdfReport,
  gdpPdfSeconds,
  gdpPdfTokens,
  gdpPdfUsd,
  gdpPdfVerdict,
} from "@/lib/gdp-pdf-page-data";
import styles from "./gdp-pdf.module.css";

/*
  The two-arm GDP.pdf run, published whichever way it came out.

  It came out negative. Adding TAVONEL's compiled context to the PDF lowered the all-criteria
  pass rate against the same model reading the PDF alone, and the headline of this page is that
  sentence, chosen by `gdpPdfDeltaSentence` from the sign of the measured delta rather than
  written. There is no copy on this page that can state a lift the artifact does not contain --
  not as a fallback, not as a default, not in a heading.

  Everything rendered here is read from `content/benchmarks/gdp-pdf.json`, which is the run
  report as the evaluation lane produced it, bound by sha256 in `lib/gdp-pdf-page-data.ts` and
  re-hashed by its test. The prose that is not read from the artifact is prose about what the run
  was, not about what it found.

  What is deliberately absent: document titles, document content, questions, answers and judge
  rationales. The corpus retains third-party rights and the raw material stays in the restricted
  run store. Task ids are pointers into that store and carry nothing on their own.

  And the label the whole page hangs under: this is NOT comparable with any published GDP.pdf
  score. The conditions panel lists every way it differs from the sealed official condition,
  generated by diffing the run manifest against `eval/gdp-pdf/protocol.json`.
*/

export const metadata = pageMetadata({
  title: "GDP.pdf: compiled context against the PDF alone",
  description:
    "A two-arm run on the public GDP.pdf task set: the same model reading the raw PDF, and reading it with TAVONEL's compiled context. Not comparable with published GDP.pdf scores.",
  canonical: "/benchmarks/gdp-pdf",
});

export default function GdpPdfBenchmarkPage() {
  const report = gdpPdfReport();
  const deviations = gdpPdfDeviations(report);
  const failureNotes = gdpPdfFailureNotes(report);
  const { macro_delta_pp: macroDelta, micro_delta_pp: microDelta, paired_n: pairedN } = report.pairwise_delta;
  const verdict = gdpPdfVerdict(macroDelta);
  const domains = Object.keys(report.per_domain).sort();
  const hardest = report.hardest_documents ?? [];
  const subset = report.compiled_available_subset;
  const truncated = report.packet_size?.packets_truncated_by_budget;

  return (
    <PublicSitePage>
      <section className="scene doc">
        <div className="shell">
          <div className="body">
            <div className="stack">
              {/* Chosen by the sign of the delta, like the sentence below it. A hand-written
                  headline is the one line that survives an artifact swap while ceasing to be
                  true, and on this page that would be the whole failure. */}
              <h1 className="document-title">{gdpPdfHeadline(macroDelta)}</h1>
            </div>

            <div className="stack">
              <p className="lede">
                GDP.pdf is a public set of 100 held-out professional tasks over ten domains,
                published by Surge. We ran two arms of it: one frontier model answering from the
                original PDF, and the same model answering from the same PDF with TAVONEL&rsquo;s
                compiled context added. Same model, same surface, same rubric, same grader. This
                page is the result and the conditions it was produced under.
              </p>

              {/*
                The label first, before any number. A reader who stops at the first panel should
                leave knowing the one thing that would make every figure below misleading if it
                were forgotten.
              */}
              <p className={styles.notComparable}>
                <b>Not comparable with published GDP.pdf scores.</b> This run deviates from the
                sealed official condition in {deviations.length} ways, listed below. Nothing here
                may be quoted beside a leaderboard row, and no figure on this page is a
                reproduction of anyone else&rsquo;s.
              </p>

              <h2 className={styles.sectionTitle}>The conditions this was run under</h2>
              <p className={styles.para}>
                Each row is a difference between the run manifest and the sealed protocol in{" "}
                <code>eval/gdp-pdf/protocol.json</code>.
              </p>
              <div className={styles.tableScroll}>
                <table className={styles.table}>
                  <caption>Deviations from the official condition</caption>
                  <thead>
                    <tr>
                      <th scope="col">Condition</th>
                      <th scope="col">Official</th>
                      <th scope="col">This run</th>
                    </tr>
                  </thead>
                  <tbody>
                    {deviations.map((deviation) => (
                      <tr key={deviation.id}>
                        <th scope="row">{deviation.label}</th>
                        <td className={styles.wrap}>{deviation.official}</td>
                        <td className={styles.wrap}>
                          {deviation.actual}
                          {deviation.note ? <span className={styles.note}>{deviation.note}</span> : null}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>

              <h2 className={styles.sectionTitle}>What the run found</h2>
              {/*
                One sentence, three possible forms, selected by the sign of the delta. The
                committed artifact takes the "worse" branch and the heading above it is written to
                be true of that branch; `lib/gdp-pdf-page-data.test.ts` holds all three.
              */}
              <p className={styles.finding} data-verdict={verdict}>
                {gdpPdfDeltaSentence(macroDelta, pairedN, "the all-criteria pass rate")}
              </p>
              <p className={styles.para}>
                <b>Macro</b> is the share of tasks where every rubric criterion passed &mdash; the
                official headline metric, and a hard one: one missed criterion out of eighteen
                fails the task. <b>Micro</b> is the mean fraction of criteria passed, which moves
                for partial credit. A subject, adapter or judge failure scores zero and stays in
                the denominator.
              </p>
              <div className={styles.tableScroll}>
                <table className={styles.table}>
                  <caption>Headline, per arm</caption>
                  <thead>
                    <tr>
                      <th scope="col">Arm</th>
                      <th scope="col">n</th>
                      <th scope="col">Macro all-criteria pass</th>
                      <th scope="col">Micro mean criteria</th>
                      <th scope="col">Criteria passed</th>
                    </tr>
                  </thead>
                  <tbody>
                    {GDP_PDF_PAGE_ARMS.map((arm) => {
                      const summary = report.arms[arm];
                      return (
                        <tr key={arm}>
                          <th scope="row">{GDP_PDF_ARM_LABEL[arm]}</th>
                          <td className={styles.value}>{summary.n}</td>
                          <td className={styles.value}>
                            {gdpPdfPercent(summary.macro_all_pass)}{" "}
                            <span className={styles.over}>({summary.macro_all_pass_count} of {summary.n})</span>
                          </td>
                          <td className={styles.value}>{gdpPdfPercent(summary.micro_mean_criteria)}</td>
                          <td className={styles.value}>
                            {summary.criteria_passed_total} of {summary.criteria_total}
                          </td>
                        </tr>
                      );
                    })}
                    <tr>
                      <th scope="row">Delta (compiled &minus; PDF alone)</th>
                      <td className={styles.value}>{pairedN}</td>
                      <td className={styles.value}>{gdpPdfPoints(macroDelta)}</td>
                      <td className={styles.value}>{gdpPdfPoints(microDelta)}</td>
                      <td className={styles.over}>over the tasks run in both arms</td>
                    </tr>
                  </tbody>
                </table>
              </div>

              {subset && typeof subset.macro_delta_pp === "number" ? (
                <p className={styles.para}>
                  <b>A second denominator, not a second headline.</b> {subset.n} of the{" "}
                  {report.arms.compiled_context_pdf.n} tasks had a compiled packet that could
                  actually be assembled. Over those {subset.n} alone the macro delta is{" "}
                  {gdpPdfPoints(subset.macro_delta_pp)}
                  {typeof subset.micro_delta_pp === "number"
                    ? ` and the micro delta ${gdpPdfPoints(subset.micro_delta_pp)}`
                    : ""}
                  . That cut separates &ldquo;no packet existed&rdquo; from &ldquo;the packet did
                  not help&rdquo;.
                </p>
              ) : null}

              <h2 className={styles.sectionTitle}>Per domain</h2>
              <p className={styles.para}>
                Counts, not just rates. Most of these denominators are one or two tasks, which is
                too few to read a domain effect from &mdash; they are published because leaving
                them out would hide where the run is thin.
              </p>
              <div className={styles.tableScroll}>
                <table className={styles.table}>
                  <caption>Macro all-criteria pass, per domain and arm</caption>
                  <thead>
                    <tr>
                      <th scope="col">Domain</th>
                      <th scope="col">n</th>
                      <th scope="col">PDF alone</th>
                      <th scope="col">PDF + compiled context</th>
                    </tr>
                  </thead>
                  <tbody>
                    {domains.map((domain) => {
                      const native = report.per_domain[domain].native_pdf;
                      const compiled = report.per_domain[domain].compiled_context_pdf;
                      return (
                        <tr key={domain}>
                          <th scope="row">{domain}</th>
                          <td className={styles.value}>{native.n}</td>
                          <td className={styles.value}>
                            {native.macro_all_pass_count} of {native.n}{" "}
                            <span className={styles.over}>({gdpPdfPercent(native.micro_mean_criteria)} micro)</span>
                          </td>
                          <td className={styles.value}>
                            {compiled.macro_all_pass_count} of {compiled.n}{" "}
                            <span className={styles.over}>({gdpPdfPercent(compiled.micro_mean_criteria)} micro)</span>
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>

              <h2 className={styles.sectionTitle}>Tokens, latency and cost</h2>
              <p className={styles.para}>
                The money column is a <b>list-price equivalent</b>, never an invoice amount. The
                run executed on a subscription surface where the marginal cost of a call is $0; the
                figure is what the same tokens would have cost at the API list price in the run&rsquo;s
                price snapshot. That snapshot carries no cache-token price, so where cost is marked
                incomplete the figure covers uncached input and output only and{" "}
                <b>understates the run</b>. Latency is wall-clock per task, including the model
                paging through the PDF.
              </p>
              <div className={styles.tableScroll}>
                <table className={styles.table}>
                  <caption>Tokens, latency and list-price-equivalent cost, per arm</caption>
                  <thead>
                    <tr>
                      <th scope="col">Arm</th>
                      <th scope="col">n</th>
                      <th scope="col">Input tokens</th>
                      <th scope="col">Output tokens</th>
                      <th scope="col">p50</th>
                      <th scope="col">p95</th>
                      <th scope="col">Subject (list-equiv)</th>
                      <th scope="col">Judge (list-equiv)</th>
                      <th scope="col">Cost complete</th>
                    </tr>
                  </thead>
                  <tbody>
                    {GDP_PDF_PAGE_ARMS.map((arm) => {
                      const summary = report.arms[arm];
                      return (
                        <tr key={arm}>
                          <th scope="row">{GDP_PDF_ARM_LABEL[arm]}</th>
                          <td className={styles.value}>{summary.n}</td>
                          <td className={styles.value}>
                            {gdpPdfTokens(summary.input_tokens_total)}{" "}
                            <span className={styles.over}>(reported for {summary.input_tokens_reported_for} of {summary.n})</span>
                          </td>
                          <td className={styles.value}>{gdpPdfTokens(summary.output_tokens_total)}</td>
                          <td className={styles.value}>{gdpPdfSeconds(summary.latency_p50_seconds)}</td>
                          <td className={styles.value}>{gdpPdfSeconds(summary.latency_p95_seconds)}</td>
                          <td className={styles.value}>{gdpPdfUsd(summary.subject_cost_usd_micros_total)}</td>
                          <td className={styles.value}>{gdpPdfUsd(summary.judge_cost_usd_micros_total)}</td>
                          <td className={styles.value}>{summary.cost_complete ? "yes" : "no"}</td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>

              <h2 className={styles.sectionTitle}>Hardest documents</h2>
              {hardest.length > 0 ? (
                <>
                  <p className={styles.para}>
                    Task ids only. The documents themselves are third-party material in a
                    restricted run store, and no title, question or answer is published here.
                  </p>
                  <div className={styles.tableScroll}>
                    <table className={styles.table}>
                      <caption>Ranked by the PDF-alone arm&rsquo;s mean criteria</caption>
                      <thead>
                        <tr>
                          <th scope="col">Task</th>
                          <th scope="col">Domain</th>
                          <th scope="col">Pages</th>
                          <th scope="col">Scanned</th>
                          <th scope="col">Criteria</th>
                          <th scope="col">PDF alone</th>
                          <th scope="col">PDF + compiled</th>
                        </tr>
                      </thead>
                      <tbody>
                        {hardest.map((row) => (
                          <tr key={row.task_id}>
                            <th scope="row"><code>{row.task_id.slice(0, 8)}</code></th>
                            <td>{row.domain}</td>
                            <td className={styles.value}>{row.pages}</td>
                            <td className={styles.value}>
                              {row.scanned === undefined ? "not recorded" : row.scanned ? "yes" : "no"}
                            </td>
                            <td className={styles.value}>{row.criteria}</td>
                            <td className={styles.value}>
                              {row.native_pdf_passed} of {row.criteria}{" "}
                              <span className={styles.over}>({row.native_pdf_all_pass ? "all pass" : "not all"})</span>
                            </td>
                            <td className={styles.value}>
                              {row.compiled_context_pdf_passed === undefined ? (
                                "not recorded"
                              ) : (
                                <>
                                  {row.compiled_context_pdf_passed} of {row.criteria}{" "}
                                  <span className={styles.over}>
                                    ({row.compiled_context_pdf_all_pass ? "all pass" : "not all"})
                                  </span>
                                </>
                              )}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </>
              ) : (
                /*
                  Not a placeholder. The run report this page is bound to does not carry per-task
                  rows -- the report builder ranks them for its own markdown and does not write
                  them into the JSON -- and the honest render of an absent table is a sentence
                  saying it is absent, not a table of plausible rows.
                */
                <p className={styles.state}>Per-task rows are not published for this run.</p>
              )}

              <h2 className={styles.sectionTitle}>What this does and does not show</h2>
              <ul className={styles.plainList}>
                <li>
                  <b>It shows</b> that on {pairedN} tasks of this set, under this surface and this
                  grader, the compiled-context arm did not beat the model reading the PDF directly.
                  That is a finding about our compiled context.
                </li>
                <li>
                  <b>It does not show</b> a GDP.pdf score. {deviations.length} conditions differ
                  from the official protocol, any one of which is enough to make a comparison with
                  a published row meaningless.
                </li>
                <li>
                  <b>It does not show</b> a stable effect size. {pairedN} tasks at one epoch each,
                  with no confidence interval, is an early read. Every rate on this page is over
                  the tasks actually run.
                </li>
                <li>
                  <b>It does not show</b> anything about the other two sealed arms. Fixed-control
                  retrieval and the adaptive router were not run in this lane. They are not run,
                  which is different from zero.
                </li>
                {truncated !== undefined && report.packet_size !== undefined && truncated > 0 ? (
                  <li>
                    <b>It does not show</b> the compiled context at full size.{" "}
                    <span data-derived="1">{truncated}</span> of the{" "}
                    <span data-derived="1">{report.packet_size.n}</span> packets reached the
                    adapter&rsquo;s character budget and were cut before the model read them, so on
                    those tasks the arm answered from a truncated packet. That is a condition of
                    this run, recorded here; it is not a correction to the result above.
                  </li>
                ) : null}
                {failureNotes.map((note) => (
                  <li key={note}>{note}</li>
                ))}
              </ul>

              <h2 className={styles.sectionTitle}>Receipts</h2>
              <details className="status-fold">
                <summary>What this page&rsquo;s figures are bound to</summary>
                <dl className={styles.receipt}>
                  <div className={styles.receiptRow}>
                    <dt>Artifact</dt>
                    <dd>
                      <code>{GDP_PDF_ARTIFACT_PATH}</code>
                      <br />
                      <code className={styles.digest}>sha256:{GDP_PDF_ARTIFACT_SHA256}</code>
                    </dd>
                  </div>
                  <div className={styles.receiptRow}>
                    <dt>Subject model</dt>
                    <dd><code>{report.manifest.surface.declared_model}</code></dd>
                  </div>
                  <div className={styles.receiptRow}>
                    <dt>Surface</dt>
                    <dd>
                      <code>{report.manifest.surface.surface}</code> · tools:{" "}
                      <code>{report.manifest.surface.tools.join(", ") || "none"}</code>
                    </dd>
                  </div>
                  <div className={styles.receiptRow}>
                    <dt>Judge</dt>
                    <dd>{report.manifest.judge}</dd>
                  </div>
                  <div className={styles.receiptRow}>
                    <dt>Dataset revision run</dt>
                    <dd><code className={styles.digest}>{report.manifest.dataset_revision}</code></dd>
                  </div>
                  <div className={styles.receiptRow}>
                    <dt>Sealed dataset revision</dt>
                    <dd><code className={styles.digest}>{report.manifest.sealed_revision}</code></dd>
                  </div>
                  <div className={styles.receiptRow}>
                    <dt>Task set digest</dt>
                    <dd><code className={styles.digest}>{report.manifest.task_set_digest}</code></dd>
                  </div>
                  {Object.entries(report.manifest.prompt_template_digests).map(([name, digest]) => (
                    <div className={styles.receiptRow} key={name}>
                      <dt>Prompt digest · {name}</dt>
                      <dd><code className={styles.digest}>{digest}</code></dd>
                    </div>
                  ))}
                  <div className={styles.receiptRow}>
                    <dt>Epochs · seed</dt>
                    <dd>
                      {report.manifest.epoch} · <code>{report.manifest.seed}</code>
                    </dd>
                  </div>
                  <div className={styles.receiptRow}>
                    <dt>Cells recorded</dt>
                    <dd>
                      {report.cells_recorded} · {report.manifest.tasks_attempted} of{" "}
                      {report.manifest.task_count_in_catalog} catalogue tasks, both arms
                    </dd>
                  </div>
                </dl>
              </details>
              <p className={styles.para}>
                The protocol these arms are sealed against, the source pins and the rights position
                on the corpus are in <code>nextjs/eval/gdp-pdf/README.md</code> and{" "}
                <code>nextjs/eval/gdp-pdf/protocol.json</code> in this repository, which is also
                what the conditions table above is diffed against. Prompts, PDFs, answers and judge
                rationales stay in the restricted run store; only their digests appear here.
              </p>
              <p className={styles.para}>
                The corpus is{" "}
                <a href="https://huggingface.co/datasets/surgeai/GDP.pdf">GDP.pdf, by Surge</a>,
                used under the dataset&rsquo;s own terms: not redistributed, not used for training.
                The{" "}
                <a href="https://github.com/surge-ai/gdp-pdf">reference harness</a> is recorded as
                evidence and its code is not copied.
              </p>

              <p className="fine">
                <b>Also in the trust case:</b>{" "}
                <Link href={"/benchmarks" as Route}>Benchmark protocol</Link> ·{" "}
                <Link href={"/evidence" as Route}>Evidence</Link> ·{" "}
                <Link href={"/reproducibility" as Route}>Reproducibility</Link> ·{" "}
                <Link href={"/research/notes" as Route}>Research notes</Link>
              </p>
            </div>
          </div>
        </div>
      </section>
    </PublicSitePage>
  );
}
